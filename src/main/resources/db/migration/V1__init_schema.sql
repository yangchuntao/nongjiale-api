CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone         VARCHAR(20)  NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_app_user_phone UNIQUE (phone)
);

CREATE TABLE admin_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    role          VARCHAR(32)  NOT NULL, -- OPERATOR | AGENT
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_admin_user_username UNIQUE (username)
);

CREATE TABLE region (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug       VARCHAR(64)  NOT NULL,
    name       VARCHAR(64)  NOT NULL,
    sort_order INT          NOT NULL DEFAULT 0,
    enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_region_slug UNIQUE (slug)
);

CREATE TABLE homestay (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id    BIGINT       NOT NULL,
    name         VARCHAR(128) NOT NULL,
    address      VARCHAR(256) NOT NULL,
    cover_url    VARCHAR(512),
    sales_count  INT          NOT NULL DEFAULT 0,
    status       VARCHAR(16)  NOT NULL, -- ON_SALE | OFF_SALE | DRAFT
    price_from   DECIMAL(10,2),
    facilities   CLOB,
    notice       CLOB,
    version      BIGINT       NOT NULL DEFAULT 0,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_homestay_region FOREIGN KEY (region_id) REFERENCES region(id)
);

CREATE TABLE homestay_room (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    homestay_id  BIGINT         NOT NULL,
    name         VARCHAR(64)    NOT NULL,
    room_count   INT,
    price_from   DECIMAL(10,2)  NOT NULL,
    sort_order   INT            NOT NULL DEFAULT 0,
    CONSTRAINT fk_room_homestay FOREIGN KEY (homestay_id) REFERENCES homestay(id)
);

CREATE TABLE review (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    homestay_id  BIGINT       NOT NULL,
    score        INT          NOT NULL,
    content      VARCHAR(1000),
    visible      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_review_homestay FOREIGN KEY (homestay_id) REFERENCES homestay(id)
);

CREATE TABLE article (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(200) NOT NULL,
    cover_url    VARCHAR(512),
    body         CLOB,
    status       VARCHAR(16)  NOT NULL, -- DRAFT | PUBLISHED
    published_at TIMESTAMP,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE home_slot (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_type    VARCHAR(32)  NOT NULL, -- HOT | TOPIC | ARTICLE
    target_id    BIGINT       NOT NULL,
    sort_order   INT          NOT NULL DEFAULT 0,
    enabled      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE booking_intent (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_no       VARCHAR(32)  NOT NULL,
    user_id         BIGINT       NOT NULL,
    homestay_id     BIGINT       NOT NULL,
    check_in        DATE         NOT NULL,
    check_out       DATE         NOT NULL,
    guests          INT          NOT NULL,
    travel_mode     VARCHAR(64),
    contact_name    VARCHAR(64)  NOT NULL,
    contact_phone   VARCHAR(20)  NOT NULL,
    status          VARCHAR(16)  NOT NULL, -- PENDING | CONFIRMED | RESCHEDULED | CLOSED
    idempotency_key VARCHAR(128) NOT NULL,
    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_intent_no UNIQUE (intent_no),
    CONSTRAINT uk_intent_idem UNIQUE (idempotency_key),
    CONSTRAINT fk_intent_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_intent_homestay FOREIGN KEY (homestay_id) REFERENCES homestay(id)
);

CREATE TABLE intent_note (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intent_id  BIGINT       NOT NULL,
    admin_id   BIGINT       NOT NULL,
    action     VARCHAR(32)  NOT NULL,
    note       VARCHAR(1000),
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_note_intent FOREIGN KEY (intent_id) REFERENCES booking_intent(id),
    CONSTRAINT fk_note_admin FOREIGN KEY (admin_id) REFERENCES admin_user(id)
);

CREATE TABLE contact_message (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    homestay_id   BIGINT,
    content       VARCHAR(2000) NOT NULL,
    contact_name  VARCHAR(64)  NOT NULL,
    contact_phone VARCHAR(20)  NOT NULL,
    status        VARCHAR(16)  NOT NULL, -- PENDING | DONE
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_msg_user FOREIGN KEY (user_id) REFERENCES app_user(id)
);

CREATE INDEX idx_homestay_region_status ON homestay(region_id, status);
CREATE INDEX idx_intent_status ON booking_intent(status);
CREATE INDEX idx_intent_user ON booking_intent(user_id);
