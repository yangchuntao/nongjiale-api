CREATE TABLE merchant (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_name  VARCHAR(128) NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE merchant_user (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id           BIGINT       NOT NULL,
    phone                 VARCHAR(20)  NOT NULL,
    password_hash         VARCHAR(100) NOT NULL,
    must_change_password  BOOLEAN      NOT NULL DEFAULT TRUE,
    enabled               BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_merchant_user_phone UNIQUE (phone),
    CONSTRAINT fk_merchant_user_merchant FOREIGN KEY (merchant_id) REFERENCES merchant(id)
);

CREATE TABLE merchant_application (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT,
    subject_name         VARCHAR(128) NOT NULL,
    contact_name         VARCHAR(64)  NOT NULL,
    phone                VARCHAR(20)  NOT NULL,
    proposed_store_name  VARCHAR(128) NOT NULL,
    region_id            BIGINT       NOT NULL,
    description          VARCHAR(2000),
    license_text         VARCHAR(2000),
    license_image_urls   CLOB,
    status               VARCHAR(16)  NOT NULL,
    reject_reason        VARCHAR(1000),
    merchant_id          BIGINT,
    reviewed_at          TIMESTAMP,
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_mapp_user FOREIGN KEY (user_id) REFERENCES app_user(id),
    CONSTRAINT fk_mapp_region FOREIGN KEY (region_id) REFERENCES region(id)
);

CREATE TABLE listing_application (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    homestay_id    BIGINT       NOT NULL,
    merchant_id    BIGINT       NOT NULL,
    action         VARCHAR(16)  NOT NULL,
    status         VARCHAR(16)  NOT NULL,
    note           VARCHAR(1000),
    reject_reason  VARCHAR(1000),
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at    TIMESTAMP,
    CONSTRAINT fk_listing_homestay FOREIGN KEY (homestay_id) REFERENCES homestay(id),
    CONSTRAINT fk_listing_merchant FOREIGN KEY (merchant_id) REFERENCES merchant(id)
);

CREATE TABLE homestay_tag (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    homestay_id  BIGINT      NOT NULL,
    tag          VARCHAR(64) NOT NULL,
    CONSTRAINT uk_homestay_tag UNIQUE (homestay_id, tag),
    CONSTRAINT fk_tag_homestay FOREIGN KEY (homestay_id) REFERENCES homestay(id)
);

CREATE TABLE site_config (
    id             BIGINT PRIMARY KEY,
    site_name      VARCHAR(128) NOT NULL DEFAULT '',
    primary_color  VARCHAR(16)  NOT NULL DEFAULT '',
    contact_phone  VARCHAR(32)  NOT NULL
);

